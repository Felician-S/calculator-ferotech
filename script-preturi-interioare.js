var SUPRAFATA_MINIMA_ROLETE_PLISSE = 0.8;
var ADAOS_FIX_ROLETE_PLISSE = 25;

function valoareNumericaInterioare(id) {
    var element = document.getElementById(id);
    return element ? parseFloat(String(element.value).replace(',', '.')) || 0 : 0;
}

function configuratieRoletaPlisse(nr) {
    var produsCod = document.getElementById('produs_roleta_plisse_' + nr).value;
    var produsInfo = PRODUSE_UMBRIRE_INTERIOARA[produsCod] || PRODUSE_UMBRIRE_INTERIOARA.rolete_plisse;
    var materialCod = document.getElementById('material_roleta_plisse_' + nr).value;
    var material = produsInfo.materiale[materialCod];
    var latime = valoareNumericaInterioare('latime_roleta_plisse_' + nr);
    var inaltime = valoareNumericaInterioare('inaltime_roleta_plisse_' + nr);
    var cantitate = Math.max(1, Math.floor(valoareNumericaInterioare('cantitate_roleta_plisse_' + nr) || 1));
    var suprafata = latime * inaltime / 1000000;
    var suprafataFacturata = Math.max(SUPRAFATA_MINIMA_ROLETE_PLISSE, suprafata);
    return {
        produs: produsCod,
        produsInfo: produsInfo,
        materialCod: materialCod,
        material: material,
        latime: latime,
        inaltime: inaltime,
        cantitate: cantitate,
        suprafata: suprafata,
        suprafataFacturata: suprafataFacturata,
        adaosFix: produsInfo.adaosFix
    };
}

function actualizeazaProdusUmbrireInterioara(nr) {
    var produsCod = document.getElementById('produs_roleta_plisse_' + nr).value;
    var produsInfo = PRODUSE_UMBRIRE_INTERIOARA[produsCod] || PRODUSE_UMBRIRE_INTERIOARA.rolete_plisse;
    var selectorMaterial = document.getElementById('material_roleta_plisse_' + nr);
    selectorMaterial.innerHTML = '';
    Object.keys(produsInfo.materiale).forEach(function (codMaterial) {
        var material = produsInfo.materiale[codMaterial];
        var optiune = document.createElement('option');
        optiune.value = codMaterial;
        optiune.textContent = material.nume;
        selectorMaterial.appendChild(optiune);
    });
    document.getElementById('adaos_fix_roleta_plisse_' + nr).textContent = produsInfo.adaosFix.toFixed(0);
    actualizeazaMaterialRoletaPlisse(nr);
}

function calculeazaPretUnitarRoletaPlisse(config) {
    if (!config.material || !(config.latime > 0 && config.inaltime > 0)) return -1;
    var pret = config.suprafataFacturata * config.material.pretMp * 2 + config.adaosFix;
    return Math.round((pret + Number.EPSILON) * 100) / 100;
}

function formateazaSuprafataRoletaPlisse(valoare) {
    return valoare.toFixed(3).replace(/0+$/, '').replace(/\.$/, '');
}

function actualizeazaMaterialRoletaPlisse(nr) {
    var produsCod = document.getElementById('produs_roleta_plisse_' + nr).value;
    var produsInfo = PRODUSE_UMBRIRE_INTERIOARA[produsCod] || PRODUSE_UMBRIRE_INTERIOARA.rolete_plisse;
    var materialCod = document.getElementById('material_roleta_plisse_' + nr).value;
    var material = produsInfo.materiale[materialCod];
    document.getElementById('tip_material_roleta_plisse_' + nr).innerHTML = material ? material.tip : '—';
    document.getElementById('compozitie_roleta_plisse_' + nr).innerHTML = material ? material.compozitie : '—';
    document.getElementById('pret_mp_roleta_plisse_' + nr).innerHTML = material ? material.pretMp.toFixed(2) : '0.00';
    pretRoletaPlisse(nr);
}

function pretRoletaPlisse(buton) {
    var container = buton && buton.closest ? buton.closest('.roleta-plisse') : null;
    var atributNumar = container
        ? (typeof container.attr === 'function' ? container.attr('numar') : container.getAttribute('numar'))
        : buton;
    var nr = parseInt(atributNumar, 10);
    var config = configuratieRoletaPlisse(nr);
    var pretUnitar = calculeazaPretUnitarRoletaPlisse(config);
    var eroare = document.getElementById('eroare_roleta_plisse_' + nr);

    if (!(pretUnitar > 0)) {
        document.getElementById('suprafata_roleta_plisse_' + nr).innerHTML = '0';
        document.getElementById('suprafata_facturata_roleta_plisse_' + nr).innerHTML = '0';
        document.getElementById('pret_roleta_plisse_' + nr).innerHTML = '0';
        document.getElementById('pret_total_roleta_plisse_' + nr).innerHTML = '0';
        if (eroare) eroare.textContent = 'Completează materialul, lățimea și înălțimea.';
        return -1;
    }

    document.getElementById('suprafata_roleta_plisse_' + nr).innerHTML = formateazaSuprafataRoletaPlisse(config.suprafata);
    document.getElementById('suprafata_facturata_roleta_plisse_' + nr).innerHTML = formateazaSuprafataRoletaPlisse(config.suprafataFacturata);
    document.getElementById('pret_roleta_plisse_' + nr).innerHTML = pretUnitar.toFixed(2);
    document.getElementById('pret_total_roleta_plisse_' + nr).innerHTML = (pretUnitar * config.cantitate).toFixed(2);
    if (eroare) eroare.textContent = '';
    return pretUnitar * config.cantitate;
}

function pret5p(nr) {
    return pretRoletaPlisse(nr);
}
